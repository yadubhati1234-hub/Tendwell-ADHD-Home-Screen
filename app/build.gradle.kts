// Release signing comes from environment variables (CI) or an untracked
// keystore.properties file (local builds). Without either, the release
// build is produced unsigned.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)

val releaseStoreFile = signingValue("TENDWELL_KEYSTORE_PATH", "storeFile")

